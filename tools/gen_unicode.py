"""Generate src/mdzip/unicode_data.lua from Python's unicodedata.

The Lua core needs NFC normalization (spec 5.4.1) and Unicode default case
folding (spec 5.4, for case-only collision warnings). Lua has neither, so this
script writes the tables they need:

  ccc       code point -> canonical combining class (non-zero only)
  decomp    code point -> full canonical decomposition (Hangul excluded; it is algorithmic)
  comp      first -> { second -> composite } for primary composites
  fold      code point -> full case folding (statuses C and F), when it differs

Run from the repo root:  python tools/gen_unicode.py
"""
import sys
import unicodedata

OUT = "src/mdzip/unicode_data.lua"
MAX = 0x110000


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


def canonical_decomposition(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def full_decomposition(cp):
    out = []
    for part in canonical_decomposition(cp) or [cp]:
        if part != cp and canonical_decomposition(part):
            out.extend(full_decomposition(part))
        else:
            out.append(part)
    return out


def main():
    ccc = {}
    decomp = {}
    comp = {}
    fold = {}
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        c = unicodedata.combining(ch)
        if c:
            ccc[cp] = c
        if not is_hangul_syllable(cp):
            d = canonical_decomposition(cp)
            if d:
                decomp[cp] = full_decomposition(cp)
                # A primary composite: a two-part canonical decomposition that NFC recomposes.
                if len(d) == 2 and unicodedata.normalize("NFC", chr(d[0]) + chr(d[1])) == ch:
                    comp.setdefault(d[0], {})[d[1]] = cp
        f = ch.casefold()
        if f != ch:
            fold[cp] = [ord(x) for x in f]

    def lua_list(xs):
        return "{" + ",".join(str(x) for x in xs) + "}"

    lines = [
        "-- Generated by tools/gen_unicode.py from Python %s (Unicode %s). Do not edit."
        % (sys.version.split()[0], unicodedata.unidata_version),
        "local M = {}",
        'M.version = "%s"' % unicodedata.unidata_version,
        "M.ccc = {",
    ]
    lines += ["[%d]=%d," % (k, v) for k, v in sorted(ccc.items())]
    lines += ["}", "M.decomp = {"]
    lines += ["[%d]=%s," % (k, lua_list(v)) for k, v in sorted(decomp.items())]
    lines += ["}", "M.comp = {"]
    for a, seconds in sorted(comp.items()):
        inner = ",".join("[%d]=%d" % (b, c) for b, c in sorted(seconds.items()))
        lines.append("[%d]={%s}," % (a, inner))
    lines += ["}", "M.fold = {"]
    lines += ["[%d]=%s," % (k, lua_list(v)) for k, v in sorted(fold.items())]
    lines += ["}", "return M", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote %s: %d ccc, %d decompositions, %d compositions, %d folds (Unicode %s)"
          % (OUT, len(ccc), len(decomp), sum(len(v) for v in comp.values()), len(fold),
             unicodedata.unidata_version))


if __name__ == "__main__":
    main()
